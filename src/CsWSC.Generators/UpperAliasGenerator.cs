using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace CsWSC.Generators;

/// <summary>
/// スクリプトから使う型 (ScriptGlobals・ControlBase・Window・Control・Capture・BalloonDefaults・Balloon) の public なメンバー (static も含む) に、
/// UWSC 風の全部大文字の別名 (補完には出さない) を生成します。対象の型は partial にしておきます。
/// </summary>
[Generator]
public sealed class UpperAliasGenerator : IIncrementalGenerator {
	private static readonly string[] TargetTypes = ["CsWSC.ScriptGlobals", "CsWSC.ControlBase", "CsWSC.Window", "CsWSC.Control", "CsWSC.Capture", "CsWSC.BalloonDefaults", "CsWSC.Balloon"];
	private const string Hidden = "[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]";

	private static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
		.AddMiscellaneousOptions( SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier );

	public void Initialize( IncrementalGeneratorInitializationContext context ) {
		// 型ごとに出力する (生成したコードは string なので、変わらなければ出力し直さない)
		foreach( var target in TargetTypes ) {
			var source = context.CompilationProvider.Select( ( c, _ ) => {
				var type = c.GetTypeByMetadataName( target );
				return type is null ? null : Generate( type );
			} );
			var hintName = $"{target.Substring( target.LastIndexOf( '.' ) + 1 )}.Upper.g.cs";
			context.RegisterSourceOutput( source, ( spc, code ) => {
				if( code is not null ) spc.AddSource( hintName, code );
			} );
		}
	}

	private static string Generate( INamedTypeSymbol type ) {
		var existing = type.GetMembers().Select( m => m.Name ).ToImmutableHashSet();
		var sb = new StringBuilder();
		sb.AppendLine( "// <auto-generated/>" );
		sb.AppendLine( "#nullable enable" );
		sb.AppendLine( $"namespace {type.ContainingNamespace.ToDisplayString()};" );
		sb.AppendLine();
		sb.AppendLine( $"partial class {type.Name}" );
		sb.AppendLine( "{" );

		foreach( var member in type.GetMembers() ) {
			// Equals・ToString などの override は別名にしない
			if( member.DeclaredAccessibility != Accessibility.Public || member.IsImplicitlyDeclared || member.IsOverride ) continue;
			var upper = member.Name.ToUpperInvariant();
			if( upper == member.Name || existing.Contains( upper ) ) continue;
			var modifiers = member.IsStatic ? "public static" : "public";

			switch( member ) {
				case IPropertySymbol { IsIndexer: false, GetMethod: { DeclaredAccessibility: Accessibility.Public } } p:
					AppendInheritDoc( sb, member );
					// 公開 setter があれば代入もできるようにする (BALLOONDEFAULT.FONTSIZE = 14 など)
					var setter = p.SetMethod is { DeclaredAccessibility: Accessibility.Public, IsInitOnly: false } ? $" set => {p.Name} = value;" : "";
					sb.AppendLine( $"    {Hidden} {modifiers} {p.Type.ToDisplayString( TypeFormat )} {upper} {{ get => {p.Name};{setter} }}" );
					break;
				case IMethodSymbol { MethodKind: MethodKind.Ordinary, IsGenericMethod: false } m:
					var parameters = string.Join( ", ", m.Parameters.Select( FormatParameter ) );
					var arguments = string.Join( ", ", m.Parameters.Select( a => RefPrefix( a ) + "@" + a.Name ) );
					var ret = m.ReturnsVoid ? "void" : m.ReturnType.ToDisplayString( TypeFormat );
					AppendInheritDoc( sb, member );
					sb.AppendLine( $"    {Hidden} {modifiers} {ret} {upper}({parameters}) => {m.Name}({arguments});" );
					break;
			}
		}

		sb.AppendLine( "}" );
		return sb.ToString();
	}

	// 元のメンバーの説明を引き継ぐ (ホバーなどに表示するため)。cref はドキュメント ID (M:… / P:…) をそのまま書くので、コンパイラは解決せずにそのまま出力する
	private static void AppendInheritDoc( StringBuilder sb, ISymbol member ) {
		if( member.GetDocumentationCommentId() is { } id ) sb.AppendLine( $"    /// <inheritdoc cref=\"{id}\"/>" );
	}

	private static string RefPrefix( IParameterSymbol p ) => p.RefKind switch {
		RefKind.Ref => "ref ",
		RefKind.Out => "out ",
		RefKind.In => "in ",
		_ => "",
	};

	private static string FormatParameter( IParameterSymbol p ) {
		var text = $"{( p.IsParams ? "params " : "" )}{RefPrefix( p )}{p.Type.ToDisplayString( TypeFormat )} @{p.Name}";
		return p.HasExplicitDefaultValue ? $"{text} = {FormatDefault( p )}" : text;
	}

	private static string FormatDefault( IParameterSymbol p ) {
		var value = p.ExplicitDefaultValue;
		if( value is null ) return "default";
		var type = p.Type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } n ? n.TypeArguments[0] : p.Type;
		var literal = SymbolDisplay.FormatPrimitive( value, quoteStrings: true, useHexadecimalNumbers: false );
		if( value is float ) literal += "f";
		return type.TypeKind == TypeKind.Enum ? $"({type.ToDisplayString( TypeFormat )})({literal})" : literal;
	}
}
